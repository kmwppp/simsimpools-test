function getFacts(testId: string) {
  const test = getTestById(testId);
  if (!test) throw new Error(`문답 데이터를 찾을 수 없습니다: ${testId}`);
  return {
    questionCount: test.questions.length,
    duration: test.duration,
    resultNames: Object.values(test.results).map(result => result.title),
  };
}

